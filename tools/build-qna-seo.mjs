import fs from "node:fs";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
const read = (file) => fs.readFileSync(new URL(file, root), "utf8");
const write = (file, content) => fs.writeFileSync(new URL(file, root), content, "utf8");
const baseUrl = "https://www.mevakshei-panecha.co.il";

const categoryNames = new Map([
  ["mamonot", "דיני ממונות"],
  ["shabbat", "שבת"],
  ["kashrut", "איסור והיתר וכשרות"],
  ["tefila", "תפילה וברכות"],
  ["avelut", "אבלות"],
  ["sukkot", "מועדים וסוכות"],
  ["musar", "מוסר והנהגה"],
  ["kabbalah", "קבלה"],
  ["nefesh", "נפש"]
]);

function loadRegistry(dataFiles, pageKey = "") {
  const context = { window: { qnaPermalinkPage: pageKey }, console };
  vm.createContext(context);
  dataFiles.forEach((file) => vm.runInContext(read(file), context, { filename: file }));
  vm.runInContext(read("qna-permalinks.js"), context, { filename: "qna-permalinks.js" });

  (context.window.qnaCustomCategories || []).forEach((category) => {
    categoryNames.set(String(category.id || ""), String(category.name || ""));
  });
  const weeklyEntries = new Map((context.window.weeklyQnaEntries || []).map((entry) => [entry.id, entry]));
  return Object.values(context.window.qnaPermalinkEntries || {}).map((entry) => {
    const weekly = weeklyEntries.get(entry.id);
    return weekly?.targetCategoryId
      ? { ...entry, category: categoryNames.get(weekly.targetCategoryId) || entry.category }
      : entry;
  });
}

function shortCode(value) {
  const source = String(value || "");
  let hash = 2166136261;
  for (let index = 0; index < source.length; index += 1) {
    hash ^= source.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(36).padStart(7, "0").slice(0, 7);
}

function xml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function clean(value) {
  return String(value || "").replace(/\s+/gu, " ").trim();
}

function validDate(value) {
  return /^\d{4}-\d{2}-\d{2}$/u.test(String(value || ""));
}

const entries = [
  ...loadRegistry([
    "choshen-mishpat.js",
    "shabbat-qna.js",
    "issur-heter-qna.js",
    "alonim-qna.js",
    "alonim-qna-extensions.js",
    "alonim-qna-docx-imports.js",
    "alonim-qna-holiday-docx-imports.js",
    "qna-custom-categories.js",
    "weekly-qna.js"
  ]),
  ...loadRegistry(["levado-data.js"], "levado"),
  ...loadRegistry(["nefesh-qna.js"], "nefesh"),
  ...loadRegistry(["nefesh-growth-qna.js"], "growth"),
  ...loadRegistry(["emuna-qna.js"], "emuna"),
  ...loadRegistry(["zugiyut-qna.js"], "zugiyut"),
  ...loadRegistry(["children-education-qna.js"], "children")
];

const byId = new Map();
entries.forEach((entry) => {
  const id = clean(entry.id);
  if (!id) return;
  const current = byId.get(id);
  if (!current || clean(entry.answer).length > clean(current.answer).length) byId.set(id, entry);
});

const byCode = Object.create(null);
for (const entry of byId.values()) {
  const code = shortCode(entry.id);
  if (byCode[code] && byCode[code].id !== entry.id) {
    throw new Error(`Short-link collision: ${code} (${byCode[code].id}, ${entry.id})`);
  }
  byCode[code] = {
    id: clean(entry.id),
    code,
    title: clean(entry.title || entry.question || "שאלה ותשובה"),
    question: clean(entry.question || entry.title),
    answer: clean(entry.answer),
    category: clean(entry.category || "שאלות ותשובות"),
    publishedAt: clean(entry.publishedAt),
    page: clean(entry.page || "qna.html"),
    topic: clean(entry.topic)
  };
}

const generatedAt = new Date().toISOString();
const indexSource = `// Generated by tools/build-qna-seo.mjs. Do not edit manually.\nexport default ${JSON.stringify({ generatedAt, entries: byCode }, null, 2)};\n`;
write("qna-seo-index.mjs", indexSource);

const sitemapSource = read("sitemap.xml");
const existingSitemap = sitemapSource.includes("<sitemapindex") && fs.existsSync(new URL("sitemap-pages.xml", root))
  ? read("sitemap-pages.xml")
  : sitemapSource;
const pageUrlBlocks = [...existingSitemap.matchAll(/\s*<url>[\s\S]*?<\/url>/gu)]
  .map((match) => match[0].trim())
  .filter((block) => !block.includes("?question=") && !block.includes(`${baseUrl}/q/`));
const pagesSitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pageUrlBlocks.map((block) => `  ${block}`).join("\n")}\n</urlset>\n`;
write("sitemap-pages.xml", pagesSitemap);

const sortedEntries = Object.values(byCode).sort((left, right) => left.code.localeCompare(right.code));
const qnaUrls = sortedEntries.map((entry) => {
  const lastmod = validDate(entry.publishedAt) ? `<lastmod>${entry.publishedAt}</lastmod>` : "";
  return `  <url><loc>${baseUrl}/q/${entry.code}</loc>${lastmod}</url>`;
}).join("\n");
write("sitemap-qna.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${qnaUrls}\n</urlset>\n`);
write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <sitemap><loc>${baseUrl}/sitemap-pages.xml</loc></sitemap>\n  <sitemap><loc>${baseUrl}/sitemap-qna.xml</loc></sitemap>\n</sitemapindex>\n`);

const feedEntries = Object.values(byCode)
  .filter((entry) => validDate(entry.publishedAt))
  .sort((left, right) => right.publishedAt.localeCompare(left.publishedAt))
  .slice(0, 100);
const feedItems = feedEntries.map((entry) => {
  const link = `${baseUrl}/q/${entry.code}`;
  const description = clean(entry.question).slice(0, 500);
  return `    <item>\n      <title>${xml(entry.title)}</title>\n      <link>${link}</link>\n      <guid isPermaLink="true">${link}</guid>\n      <pubDate>${new Date(`${entry.publishedAt}T12:00:00+03:00`).toUTCString()}</pubDate>\n      <category>${xml(entry.category)}</category>\n      <description>${xml(description)}</description>\n    </item>`;
}).join("\n");
write("feed.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">\n  <channel>\n    <title>שו״ת מבקשי פניך - הרב איתי בן יוסף</title>\n    <link>${baseUrl}/qna.html</link>\n    <description>שאלות ותשובות חדשות מאת הרב איתי בן יוסף</description>\n    <language>he</language>\n    <atom:link href="${baseUrl}/feed.xml" rel="self" type="application/rss+xml"/>\n${feedItems}\n  </channel>\n</rss>\n`);

console.log(`Generated ${Object.keys(byCode).length} SEO-ready Q&A pages, ${pageUrlBlocks.length} regular URLs and ${feedEntries.length} feed items.`);
